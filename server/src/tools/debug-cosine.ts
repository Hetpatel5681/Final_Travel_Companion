import mongoose from 'mongoose';
import dotenv from 'dotenv';
import User from '../models/User';
import { TravelProfile } from '../modules/travel-profile/travelProfile.model';
import { featureEngineeringService } from '../modules/recommendations/feature-engineering.service';
import { interactionService } from '../modules/interactions/interaction.service';

dotenv.config();

async function run() {
    await mongoose.connect(process.env.MONGODB_URI as string);
    const users = await User.find({ email: { $not: /interactiondev_/ } });
    const user = users[0];

    const userProfile = await TravelProfile.findOne({ userId: user._id }).lean() as any;
    console.log("Raw Profile:", JSON.stringify(userProfile, null, 2));
    
    const interactions = await interactionService.getUserHistory(user._id.toString());
    console.log("History length:", interactions.length);

    const userVector = featureEngineeringService.engineerUserVector(userProfile || undefined, interactions);
    console.log("Base User Vector generated by FeatureEngineering:");
    console.log(userVector);

    const zeroVector = featureEngineeringService.engineerUserVector(undefined, []);
    console.log("Absolute Cold Start Vector (undefined profile):");
    console.log(zeroVector);
    
    await mongoose.disconnect();
}
run();
